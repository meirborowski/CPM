namespace cpm::build {

namespace {

// Phony names that cannot also be used for the package's main target.
bool reserved_phony(const BuildPlan& plan, const std::string& name) {
    if (name == "all" || name == "tests") return true;
    for (const auto& t : plan.tests) {
        if (t.name == name) return true;
    }
    return false;
}

std::vector<std::pair<std::string, std::string>> link_variables(const LinkStep& link) {
    std::vector<std::pair<std::string, std::string>> vars;
    if (!link.extra_ldflags.empty()) vars.emplace_back("ldflags", "$ldflags " + ninja::args_value(link.extra_ldflags));
    if (!link.extra_libs.empty()) vars.emplace_back("libs", ninja::args_value(link.extra_libs) + " $libs");
    return vars;
}

}  // namespace

std::vector<std::string> test_target_names(const BuildPlan& plan) {
    std::vector<std::string> names;
    for (const auto& t : plan.tests) names.push_back(t.name);
    return names;
}

std::string generate_ninja(const BuildPlan& plan, const toolchain::Driver& driver) {
    ninja::Writer w;
    w.comment(std::format("Generated by cpm {} for {}@{} (profile: {}, toolchain: {}). Do not edit.", version,
                          plan.package, plan.package_version, plan.profile, plan.toolchain.description()));
    w.variable("ninja_required_version", "1.10");
    w.variable("builddir", ninja::escape_value(plan.build_dir));
    w.newline();

    // The C compiler and its flags appear only when something is C (build.md §4.5).
    const bool any_c = compiles_c(plan);
    if (any_c && !plan.toolchain.c) throw Error("internal error: the plan compiles C without a C compiler");
    w.variable("cxx", ninja::args_value({paths::to_utf8(plan.toolchain.cxx)}));
    if (any_c) w.variable("cc", ninja::args_value({paths::to_utf8(plan.toolchain.c->path)}));
    w.variable("ar", ninja::args_value({paths::to_utf8(plan.toolchain.ar)}));
    w.variable("cxxflags", ninja::args_value(plan.cxxflags));
    if (any_c) w.variable("cflags", ninja::args_value(plan.cflags));
    w.variable("defines", ninja::args_value(plan.defines));
    w.variable("incs", ninja::args_value(plan.incs));
    w.variable("ldflags", ninja::args_value(plan.ldflags));
    w.variable("libs", ninja::args_value(plan.libs));
    w.newline();

    for (const auto& rule : driver.rules()) {
        if (rule.name == "cc" && !any_c) continue;
        w.rule(rule);
        w.newline();
    }

    for (const auto& c : plan.compiles) {
        std::vector<std::pair<std::string, std::string>> vars;
        if (c.kind == CompileStep::Kind::Test) {
            vars.emplace_back("incs", "$incs " + ninja::args_value(plan.test_incs));
            if (!plan.test_defines.empty()) vars.emplace_back("defines", "$defines " + ninja::args_value(plan.test_defines));
        } else if (c.kind == CompileStep::Kind::Dependency) {
            vars.emplace_back("incs", ninja::args_value(c.incs));
            vars.emplace_back("defines", ninja::args_value(c.defines));
            if (c.language == toolchain::Language::C) vars.emplace_back("cflags", ninja::args_value(c.cflags));
        }
        std::vector<std::string> implicit;
        if (!plan.dependency_stamp.empty()) implicit.push_back(plan.dependency_stamp);
        w.build({c.object}, c.language == toolchain::Language::C ? "cc" : "cxx", {c.source}, implicit, vars);
    }
    w.newline();

    for (const auto& ar : plan.dependency_archives) w.build({ar.output}, "ar", ar.members);
    if (!plan.dependency_archives.empty()) w.newline();

    if (plan.archive) {
        w.build({plan.archive->output}, "ar", plan.archive->members);
        w.newline();
    }
    auto with_stamp = [&](std::vector<std::string> implicit) {
        if (!plan.dependency_stamp.empty()) implicit.push_back(plan.dependency_stamp);
        return implicit;
    };
    if (plan.main) {
        w.build({plan.main->output}, plan.main->shared ? "link_shared" : "link", plan.main->inputs,
                with_stamp(plan.main->implicit), link_variables(*plan.main), plan.main->implicit_outputs);
        w.newline();
    }
    for (const auto& t : plan.tests) w.build({t.output}, "link", t.inputs, with_stamp(t.implicit), link_variables(t));
    if (!plan.tests.empty()) w.newline();

    std::vector<std::string> all;
    if (!plan.main_output.empty()) {
        if (reserved_phony(plan, plan.package)) {
            all.push_back(plan.main_output);
        } else {
            w.build({plan.package}, "phony", {plan.main_output});
            all.push_back(plan.package);
        }
    }
    for (const auto& t : plan.tests) w.build({t.name}, "phony", {t.output});
    w.build({"all"}, "phony", all);
    w.build({"tests"}, "phony", test_target_names(plan));
    w.defaults({"all"});
    return w.str();
}

}  // namespace cpm::build
