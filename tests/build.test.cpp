TEST(ninja_escaping) {
    CHECK_EQ(build::ninja::escape_path("C:/a b/$x"), "C$:/a$ b/$$x");
    CHECK_EQ(build::ninja::escape_value("a $b: c"), "a $$b: c");
    CHECK_EQ(build::ninja::args_value({"-Isrc", "-DX=1"}), "-Isrc -DX=1");
}

TEST(generates_deterministic_build_ninja) {
    check::TempDir dir;
    for (const char* f : {"src/main.cpp", "src/util.cpp", "tests/util.test.cpp"}) touch(dir.path() / f);
    auto m = make_manifest(dir.path(), R"(, "std": "c++23", "systemLibs": ["m"], "defines": ["APP=1"])");
    auto layout = build::infer_layout(m, {});
    auto tc = fake_linux_gcc();
    auto driver = toolchain::make_driver(tc);
    auto plan = build::make_plan(m, m.profiles.at("release"), tc, {.cxx = "-std=c++23"}, *driver, layout);
    CHECK_EQ(plan.main_output, "build/release/hello");
    CHECK_EQ(plan.tests.size(), 1u);

    std::string expected = std::format(R"(# Generated by cpm {} for hello@1.2.3 (profile: release, toolchain: gcc 13.2.0). Do not edit.
ninja_required_version = 1.10
builddir = cpm_modules/.cache/release

cxx = /usr/bin/g++
ar = /usr/bin/gcc-ar
cxxflags = -std=c++23 -O3 -Wall -Wextra -fdiagnostics-color=always
defines = -DNDEBUG -DAPP=1
incs = -Isrc
ldflags =
libs = -lm

rule cxx
  command = $cxx -MD -MF $out.d $cxxflags $defines $incs -c $in -o $out
  description = CXX $in
  depfile = $out.d
  deps = gcc

rule ar
  command = $ar rcs $out @$out.rsp
  description = AR $out
  rspfile = $out.rsp
  rspfile_content = $in

rule link
  command = $cxx @$out.rsp -o $out $ldflags
  description = LINK $out
  rspfile = $out.rsp
  rspfile_content = $in $libs

rule link_shared
  command = $cxx -shared @$out.rsp -o $out $ldflags
  description = LINK $out
  rspfile = $out.rsp
  rspfile_content = $in $libs

build cpm_modules/.cache/release/obj/src/main.cpp.o: cxx src/main.cpp
build cpm_modules/.cache/release/obj/src/util.cpp.o: cxx src/util.cpp
build cpm_modules/.cache/release/obj/tests/util.test.cpp.o: cxx tests/util.test.cpp
  incs = $incs -Itests

build build/release/hello: link $
    cpm_modules/.cache/release/obj/src/main.cpp.o $
    cpm_modules/.cache/release/obj/src/util.cpp.o

build build/release/tests/util.test: link $
    cpm_modules/.cache/release/obj/tests/util.test.cpp.o $
    cpm_modules/.cache/release/obj/src/util.cpp.o

build hello: phony build/release/hello
build util.test: phony build/release/tests/util.test
build all: phony hello
build tests: phony util.test
default all
)", cpm::version);
    std::string generated = build::generate_ninja(plan, *driver);
    CHECK_EQ(generated, expected);
    CHECK_EQ(build::generate_ninja(build::make_plan(m, m.profiles.at("release"), tc, {.cxx = "-std=c++23"}, *driver, layout),
                                   *driver),
             generated);
}

TEST(static_and_shared_library_plans) {
    check::TempDir dir;
    touch(dir.path() / "src/lib.cpp");
    touch(dir.path() / "tests/lib.test.cpp");
    auto tc = fake_linux_gcc();
    auto driver = toolchain::make_driver(tc);

    auto m = make_manifest(dir.path());
    auto plan = build::make_plan(m, m.profiles.at("debug"), tc, {.cxx = "-std=c++20"}, *driver, build::infer_layout(m, {}));
    CHECK(plan.archive.has_value());
    CHECK_EQ(plan.main_output, "build/debug/libhello.a");
    CHECK_EQ(plan.tests[0].inputs.back(), "build/debug/libhello.a");

    auto shared = make_manifest(dir.path(), R"(, "type": "shared-lib")");
    auto splan = build::make_plan(shared, shared.profiles.at("debug"), tc, {.cxx = "-std=c++20"}, *driver,
                                  build::infer_layout(shared, {}));
    CHECK_EQ(splan.main_output, "build/debug/libhello.so");
    CHECK(std::find(splan.cxxflags.begin(), splan.cxxflags.end(), "-fPIC") != splan.cxxflags.end());
    // The soname makes dependents record "libhello.so" (found through their rpath), not the build path.
    CHECK_EQ(splan.main->extra_ldflags, (std::vector<std::string>{"-Wl,-soname,libhello.so"}));
    // Tests link the .so, so it must be an input of their link edge (`cpm test` builds only the tests).
    CHECK_EQ(splan.tests[0].extra_libs, (std::vector<std::string>{"build/debug/libhello.so"}));
    const auto& test_implicit = splan.tests[0].implicit;
    CHECK(std::find(test_implicit.begin(), test_implicit.end(), "build/debug/libhello.so") != test_implicit.end());
    CHECK_EQ(splan.tests[0].extra_ldflags, (std::vector<std::string>{"-Wl,-rpath,$ORIGIN/.."}));

    auto mac = tc;
    mac.os = Os::MacOS;
    auto mdriver = toolchain::make_driver(mac);
    auto mplan = build::make_plan(shared, shared.profiles.at("debug"), mac, {.cxx = "-std=c++20"}, *mdriver,
                                  build::infer_layout(shared, {}));
    CHECK_EQ(mplan.main_output, "build/debug/libhello.dylib");
    CHECK_EQ(mplan.main->extra_ldflags,
             (std::vector<std::string>{"-dynamiclib", "-Wl,-install_name,@rpath/libhello.dylib"}));
    CHECK_EQ(mplan.tests[0].extra_ldflags, (std::vector<std::string>{"-Wl,-rpath,@loader_path/.."}));
    // macOS's ar reads no response files.
    CHECK(build::generate_ninja(mplan, *mdriver).contains("rule ar\n  command = $ar rcs $out $in\n"));

    tc.os = Os::Windows;  // MinGW: DLL plus import library
    auto wdriver = toolchain::make_driver(tc);
    auto wplan = build::make_plan(shared, shared.profiles.at("debug"), tc, {.cxx = "-std=c++20"}, *wdriver,
                                  build::infer_layout(shared, {}));
    CHECK_EQ(wplan.main_output, "build/debug/libhello.dll");
    CHECK_EQ(wplan.main->extra_ldflags,
             (std::vector<std::string>{"-Wl,--out-implib,build/debug/libhello.dll.a"}));
    CHECK_EQ(wplan.tests[0].extra_libs, (std::vector<std::string>{"build/debug/libhello.dll.a"}));
    CHECK_EQ(wplan.main->implicit_outputs, (std::vector<std::string>{"build/debug/libhello.dll.a"}));
    std::string ninja = build::generate_ninja(wplan, *wdriver);
    CHECK(ninja.contains("build build/debug/libhello.dll | build/debug/libhello.dll.a: link_shared"));
}

TEST(profile_flag_mapping) {
    auto tc = fake_linux_gcc();
    auto driver = toolchain::make_driver(tc);
    manifest::Profile p;
    p.opt = "z";
    p.lto = true;
    p.sanitizers = {"address", "thread"};
    p.warnings = "none";
    p.werror = true;
    p.runtime = "static";
    auto f = driver->profile_flags(p, toolchain::Language::Cxx, "-std=c++20", false);
    CHECK_EQ(f.compile, (std::vector<std::string>{"-std=c++20", "-Oz", "-g", "-flto=auto", "-fsanitize=address",
                                                  "-fno-omit-frame-pointer", "-w", "-Werror",
                                                  "-fdiagnostics-color=always"}));
    CHECK_EQ(f.link, (std::vector<std::string>{"-flto=auto", "-fsanitize=address", "-static-libstdc++", "-static-libgcc"}));
    CHECK_EQ(f.notes.size(), 1u);  // thread + address

    tc.os = Os::Windows;
    auto mingw = toolchain::make_driver(tc)->profile_flags(p, toolchain::Language::Cxx, "-std=c++20", false);
    CHECK(std::find(mingw.link.begin(), mingw.link.end(), "-static") != mingw.link.end());
    CHECK_EQ(mingw.notes.size(), 2u);  // no sanitizers on MinGW
}

TEST(parses_probe_output) {
    std::string macros = "#define __GNUC__ 13\n#define __GNUC_MINOR__ 2\n#define __GNUC_PATCHLEVEL__ 0\n"
                         "#define _WIN32 1\n#define __x86_64__ 1\n#define __GLIBCXX__ 20230727\n"
                         "#define _GLIBCXX_USE_CXX11_ABI 1\n#define _UCRT \n#define __SEH__ 1\n";
    std::string verbose = "Using built-in specs.\nTarget: x86_64-w64-mingw32\nThread model: posix\n";
    auto tc = toolchain::toolchain_from_probe(toolchain::parse_probe_output(macros, verbose), "C:/g++.exe");
    CHECK(tc.family == toolchain::Family::Gcc);
    CHECK_EQ(tc.version, "13.2.0");
    CHECK(tc.os == Os::Windows);
    CHECK_EQ(tc.arch, "x86_64");
    CHECK_EQ(tc.target, "x86_64-w64-mingw32");
    CHECK_EQ(tc.stdlib, "libstdc++");
    CHECK_EQ(tc.stdlib_abi, "cxx11");
    CHECK_EQ(tc.crt, "ucrt");
    CHECK_EQ(tc.eh, "seh");
    CHECK_EQ(tc.threads, "posix");
    CHECK(tc.is_mingw());

    std::string clang = "#define __clang__ 1\n#define __clang_major__ 18\n#define __clang_minor__ 1\n"
                        "#define __clang_patchlevel__ 3\n#define __GNUC__ 4\n#define __linux__ 1\n"
                        "#define __aarch64__ 1\n#define _LIBCPP_VERSION 180100\n#define _LIBCPP_ABI_VERSION 1\n"
                        "#define __GLIBC__ 2\n";
    auto ctc = toolchain::toolchain_from_probe(toolchain::parse_probe_output(clang, "Target: aarch64-unknown-linux-gnu\n"),
                                               "/usr/bin/clang++");
    CHECK(ctc.family == toolchain::Family::Clang);
    CHECK_EQ(ctc.version, "18.1.3");
    CHECK_EQ(ctc.stdlib, "libc++");
    CHECK_EQ(ctc.stdlib_abi, "v1");
    CHECK_EQ(ctc.crt, "glibc");
    CHECK_EQ(ctc.eh, "itanium");
    CHECK(!toolchain::targets_msvc(tc));
    CHECK(!toolchain::targets_msvc(ctc));

    // LLVM's Windows installer: clang++ targeting the MSVC ABI, which auto-detection skips.
    std::string msvc_clang = "#define __clang__ 1\n#define __clang_major__ 19\n#define __clang_minor__ 1\n"
                             "#define __clang_patchlevel__ 5\n#define _MSC_VER 1940\n#define _WIN32 1\n#define _M_X64 100\n";
    auto mtc = toolchain::toolchain_from_probe(
        toolchain::parse_probe_output(msvc_clang, "clang version 19.1.5\nTarget: x86_64-pc-windows-msvc\n"),
        "C:/Program Files/LLVM/bin/clang++.exe");
    CHECK(mtc.family == toolchain::Family::Clang);
    CHECK(toolchain::targets_msvc(mtc));
}
