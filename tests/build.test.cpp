namespace {

void touch(const fs::path& p) {
    fs::create_directories(p.parent_path());
    std::ofstream(p) << "// test\n";
}

manifest::Manifest make_manifest(const fs::path& root, std::string extra = "") {
    std::string text = R"({ "name": "hello", "version": "1.2.3")" + extra + " }";
    return manifest::parse(text, root / "cpm.jsonc", "cpm.jsonc");
}

toolchain::Toolchain fake_linux_gcc() {
    toolchain::Toolchain tc;
    tc.family = toolchain::Family::Gcc;
    tc.cxx = "/usr/bin/g++";
    tc.ar = "/usr/bin/gcc-ar";
    tc.version = "13.2.0";
    tc.target = "x86_64-linux-gnu";
    tc.os = Os::Linux;
    return tc;
}

}  // namespace

TEST(infers_executable_with_core_and_tests) {
    check::TempDir dir;
    for (const char* f : {"src/main.cpp", "src/util.cpp", "src/sub/more.cc", "tests/util.test.cpp",
                          "tests/support/helper.cpp", "include/hello/hello.hpp"})
        touch(dir.path() / f);
    auto m = make_manifest(dir.path());
    auto layout = build::infer_layout(m, {});
    CHECK(layout.kind == TargetKind::Executable);
    CHECK_EQ(layout.entry.value_or(""), "src/main.cpp");
    CHECK_EQ(layout.sources, (std::vector<std::string>{"src/sub/more.cc", "src/util.cpp"}));
    CHECK_EQ(layout.tests, (std::vector<std::string>{"tests/util.test.cpp"}));
    CHECK(layout.include_dir_exists);
}

TEST(infers_libraries_and_header_only) {
    {
        check::TempDir dir;
        touch(dir.path() / "src/lib.cpp");
        touch(dir.path() / "src/impl.cpp");
        auto layout = build::infer_layout(make_manifest(dir.path()), {});
        CHECK(layout.kind == TargetKind::StaticLib);
        CHECK_EQ(layout.sources, (std::vector<std::string>{"src/impl.cpp", "src/lib.cpp"}));
    }
    {
        check::TempDir dir;
        touch(dir.path() / "include/h/h.hpp");
        auto layout = build::infer_layout(make_manifest(dir.path()), {});
        CHECK(layout.kind == TargetKind::HeaderOnly);
        CHECK(layout.sources.empty());
    }
    {
        check::TempDir dir;
        touch(dir.path() / "src/main.cpp");
        touch(dir.path() / "src/lib.cpp");
        auto layout = build::infer_layout(make_manifest(dir.path()), {});
        CHECK(layout.kind == TargetKind::Executable);
        CHECK_EQ(layout.notes.size(), 1u);  // both entrypoints exist
        auto as_lib = build::infer_layout(make_manifest(dir.path(), R"(, "type": "shared-lib")"), {});
        CHECK(as_lib.kind == TargetKind::SharedLib);
        CHECK_EQ(as_lib.sources.size(), 2u);
    }
}

TEST(layout_errors) {
    check::TempDir dir;
    CHECK_THROWS(build::infer_layout(make_manifest(dir.path()), {}), "cannot infer the target type");
    CHECK_THROWS(build::infer_layout(make_manifest(dir.path(), R"(, "type": "executable")"), {}), "no src/main.cpp");
    CHECK_THROWS(build::infer_layout(make_manifest(dir.path(), R"(, "main": "app/start.cpp")"), {}), "does not exist");
    touch(dir.path() / "app/start.cpp");
    CHECK_THROWS(build::infer_layout(make_manifest(dir.path(), R"(, "main": "app/start.cpp")"), {}),
                 "cannot infer the target type from \"main\"");
    auto layout = build::infer_layout(make_manifest(dir.path(), R"(, "main": "app/start.cpp", "type": "executable")"), {});
    CHECK_EQ(layout.entry.value_or(""), "app/start.cpp");
}

